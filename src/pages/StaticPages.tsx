const useSettings = () => (useRouteLoaderData('root') as SiteData).settings

function Publisher() {
  const settings = useSettings()
  return (
    <>
      <OwnerValue value={settings.publisher_name} fallback="податоците за издавачот ќе бидат објавени наскоро" />
      {settings.publisher_address ? `, ${settings.publisher_address}` : ''}
      {settings.publisher_registration ? ` (${settings.publisher_registration})` : ''}
    </>
  )
}

function ContactEmail({ kind = 'contact_email' }: { kind?: 'contact_email' | 'advertising_email' | 'editorial_email' }) {
  const settings = useSettings()
  const email = settings[kind] || settings.contact_email
  return email ? <a href={`mailto:${email}`}>{email}</a> : <Link to="/kontakt">формуларот за контакт</Link>
}

